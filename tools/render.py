FONT = {}
for ch, s in FONT_SRC.items():
    rows = [r for r in s.split(',') if r] if s else []
    rows += ['00000'] * (7 - len(rows))
    FONT[ord(ch)] = [int(r, 2) for r in rows]

GREEN = (190, 255, 200)   # P4 phosphor is white-blue; use a cool white
FG = (225, 235, 255)
BG = (8, 10, 14)


def glyph_code(c, lowercase=False):
    """Character the CRT shows for video byte c (graphics handled separately)."""
    c &= 0x7F
    if c < 0x20: c += 0x40          # 00-1F show as 40-5F
    if not lowercase and c >= 0x60: c -= 0x20
    return c


def render(screen, wide=False, scale=2, lowercase=True, fg=FG, bg=BG, sx=None, sy=None):
    """screen: 1024 bytes. Returns PIL image 384*scale x 192*scale*... (dot aspect 1:2 per scanline pair)."""
    W, H = 384, 192
    img = Image.new('RGB', (W, H), bg)
    px = img.load()
    for row in range(16):
        for col in range(64):
            c = screen[row * 64 + col]
            if wide and col & 1: continue
            cw = 12 if wide else 6
            x0 = (col * 6); y0 = row * 12
            if c & 0x80:
                for b in range(6):
                    if c & (1 << b):
                        bx = (b & 1); by = b >> 1
                        hw = cw // 2
                        for yy in range(4):
                            for xx in range(hw):
                                px[x0 + bx * hw + xx, y0 + by * 4 + yy] = fg
            else:
                g = FONT.get(glyph_code(c, lowercase), [])
                for gy, bits in enumerate(g):
                    for gx in range(5):
                        if bits & (16 >> gx):
                            if wide:
                                for k in range(2): px[x0 + gx * 2 + k, y0 + 1 + gy] = fg
                            else:
                                px[x0 + gx, y0 + 1 + gy] = fg
    # scale: each dot 2 wide, each scanline 2 tall -> 768x384 (4:2 shape close to the Model I's 4:3 screen at 64x16)
    # Default: 2 x 3 scaling = 768 x 576, the Model I's 4:3 picture with its
    # tall graphics blocks (each block is twice as tall as it is wide).
    if sx is None: sx, sy = (2, 3) if scale == 2 else (scale, scale * 3 // 2 if scale > 1 else 1.5)
    return img.resize((int(W * sx), int(H * sy)), Image.NEAREST)


def frames(path):
    data = open(path, 'rb').read()
    for i in range(0, len(data), 1025):
        yield data[i:i + 1024], bool(data[i + 1024])


